/** Lista {code, name} posortowana alfabetycznie w jezyku klienta. */
export function countryList(lang) {
  return COUNTRY_NAMES[lang] || COUNTRY_NAMES.en;
}

/** Sama nazwa kraju. Nieznany kod zwracamy bez zmian, zeby nic nie zniknelo. */
export function countryName(code, lang) {
  const lista = countryList(lang);
  return lista.find((k) => k.code === code)?.name || code;
}
